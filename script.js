function renderHostels(list = hostels) {

    const hostelList =
        document.getElementById("hostelList");

    const noResults =
        document.getElementById("noResults");

    hostelList.innerHTML = "";

    if (list.length === 0) {

        noResults.style.display = "block";

        return;
    }

    noResults.style.display = "none";


    list.forEach(hostel => {

        const card =
            document.createElement("div");

        card.className = "hostel-card";


        card.innerHTML = `

            <div
                class="hostel-image"
                style="
                    background-image:
                    url('${hostel.image}')
                "
            >

                <div class="rating">
                    ⭐ ${hostel.rating}
                </div>

            </div>


            <div class="card-content">

                <span class="tag">
                    ${getTypeName(hostel.type)}
                </span>

                <h3>
                    ${hostel.name}
                </h3>

                <p class="location">
                    📍 ${hostel.city}, India
                </p>

                <p class="description">
                    ${hostel.description}
                </p>


                <div class="amenities">

                    ${hostel.amenities
                        .map(item =>
                            `<span class="amenity">
                                ${item}
                            </span>`
                        )
                        .join("")
                    }

                </div>


                <div class="card-bottom">

                    <div class="price">
                        ₹${hostel.price}
                        <small>/ night</small>
                    </div>

                    <button
                        class="view-btn"
                        onclick="viewDetails('${hostel.name}')"
                    >
                        View
                    </button>

                </div>

            </div>
        `;


        hostelList.appendChild(card);

    });

}


function getTypeName(type) {

    if (type === "male")
        return "Male Dorm";

    if (type === "female")
        return "Female Dorm";

    return "Mixed Dorm";
}


function searchHostels() {

    const location =
        document
            .getElementById("locationInput")
            .value
            .toLowerCase()
            .trim();

    const gender =
        document
            .getElementById("genderFilter")
            .value;


    let results = hostels.filter(hostel => {

        const locationMatch =
            location === "" ||
            hostel.city
                .toLowerCase()
                .includes(location);

        const genderMatch =
            gender === "all" ||
            hostel.type === gender;

        return locationMatch && genderMatch;

    });


    renderHostels(results);

    document
        .getElementById("hostels")
        .scrollIntoView({
            behavior: "smooth"
        });

}


function filterByPrice() {

    const value =
        document
            .getElementById("priceFilter")
            .value;

    if (value === "all") {

        renderHostels();

        return;
    }


    const maxPrice =
        Number(value);


    const results =
        hostels.filter(
            hostel =>
                hostel.price <= maxPrice
        );


    renderHostels(results);

}


function quickSearch(city) {

    document
        .getElementById("locationInput")
        .value = city;

    searchHostels();

}


function viewDetails(name) {

    alert(
        "🏠 " +
        name +
        "\n\n" +
        "More booking and hostel details coming soon!"
    );

}


